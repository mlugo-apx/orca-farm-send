#!/usr/bin/env python3
"""Bundle src/core.py + src/app.py + src/panel.html + src/shell.py into the single-file plugin
OrcaSlicer requires: dist/farm_send/farm_send.py"""
import os
import re
import sys

VERSION = "0.5.0"
HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = '''# /// script
# requires-python = ">=3.12"
#
# [tool.orcaslicer.plugin]
# name = "Farm Send"
# description = "Print farm panel: send a sliced plate to several Elegoo Centauri Carbon 2 and Snapmaker U1 printers at once and start them, with live status."
# author = "Mike Lugo"
# version = "%s"
# ///
"""Farm Send for OrcaSlicer. GENERATED by build.py from src/ -- edit the sources, not this file.

Run it from the Plugins dialog to open the panel. After each slice the plate shows up in the
panel and can be uploaded, or uploaded and started, on any configured printer of the same model.
"""
''' % VERSION


def read(name):
    with open(os.path.join(HERE, "src", name), "r", encoding="utf-8") as handle:
        return handle.read()


def strip(source):
    return re.sub(r"# BUNDLE-STRIP-BEGIN.*?# BUNDLE-STRIP-END\n", "", source, flags=re.S)


def split_imports(source):
    """Hoist plain top-level 'import x' lines so the bundle has one import block."""
    imports, body = [], []
    for line in source.splitlines():
        (imports if re.match(r"^import [\w.]+$", line) else body).append(line)
    return imports, "\n".join(body).strip("\n") + "\n"


def main():
    panel = read("panel.html")
    if '"""' in panel:
        sys.exit('panel.html must not contain """')
    # Imports are collected from the WHOLE source of each module, including the parts stripped
    # from the bundle: each module's own "import x" lines live in its strip block next to the
    # cross-module imports, and dropping them leaves a NameError that only shows up at run time.
    stdlib = []
    for name in ("core.py", "app.py", "shell.py"):
        stdlib += [line for line in split_imports(read(name))[0] if line != "import orca"]
    core_body = split_imports(read("core.py").split('"""', 2)[2])[1]
    app_body = split_imports(strip(read("app.py").split('"""', 2)[2]))[1]
    shell_body = split_imports(strip(read("shell.py")))[1]
    imports = sorted(set(stdlib))
    out = HEADER + "\n".join(imports) + "\n\nimport orca\n\n" + \
        "PLUGIN_VERSION = %r\n\n" % VERSION + \
        "# ======================================================================================\n# core\n" + core_body + \
        "\n\n# ======================================================================================\n# app\n" + app_body + \
        "\n\n# ======================================================================================\n# panel\n" + \
        'PANEL_HTML = r"""' + panel + '"""\n' + \
        "\n\n# ======================================================================================\n# plugin\n" + shell_body
    target_dir = os.path.join(HERE, "dist", "farm_send")
    os.makedirs(target_dir, exist_ok=True)
    target = os.path.join(target_dir, "farm_send.py")
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(out)
    compile(out, target, "exec")
    print("built %s (%d lines)" % (target, out.count("\n")))
    # The same file under the name the OrcaSlicer Plugin Hub expects: <name>_<platform>.py.
    upload = os.path.join(HERE, "dist", "farm_send_any.py")
    with open(upload, "w", encoding="utf-8") as handle:
        handle.write(out)
    print("built %s (for the Plugin Hub)" % upload)


if __name__ == "__main__":
    main()
